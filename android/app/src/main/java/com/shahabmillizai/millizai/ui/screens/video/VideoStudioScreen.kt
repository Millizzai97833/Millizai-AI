import com.shahabmillizai.millizai.theme.TextPrimaryDark
import com.shahabmillizai.millizai.theme.TextSecondaryDark
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch

@Composable
fun VideoStudioScreen(
    onBack: () -> Unit
) {
    val context = LocalContext.current
    val coroutineScope = rememberCoroutineScope()

    var selectedTab by remember { mutableIntStateOf(0) } // 0: Text-to-Video, 1: Image-to-Video, 2: Story Creator
    var prompt by remember { mutableStateOf("A futuristic hovercraft gliding through misty neon mountains at dawn, cinematic 4K") }
    var selectedDuration by remember { mutableIntStateOf(10) } // 5, 10, 15, 20, 25, 30
    var selectedStyle by remember { mutableStateOf("Cinematic") }
    var selectedLanguage by remember { mutableStateOf("English") }
    var isGenerating by remember { mutableStateOf(false) }
    var videoGenerated by remember { mutableStateOf(false) }

    val styles = listOf("Cinematic", "Realistic", "Anime", "Fantasy", "Horror", "Comedy", "Cartoon")
    val durations = listOf(5, 10, 15, 20, 25, 30)

    LazyColumn(
        modifier = Modifier
            .fillMaxSize()
            .background(MillizaiBlackBg)
            .padding(16.dp)
    ) {
        item {
            // Header
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically
            ) {
                IconButton(onClick = onBack) {
                    Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back", tint = TextPrimaryDark)
                }
                Spacer(modifier = Modifier.width(8.dp))
                Column {
                    Text("AI Video Studio", color = TextPrimaryDark, fontSize = 18.sp, fontWeight = FontWeight.Bold)
                    Text("Online Text-to-Video, Image Animation & Story Creator", color = MillizaiCyan, fontSize = 11.sp)
                }
            }

            Spacer(modifier = Modifier.height(14.dp))

            // Provider & Limitations Notice
            Card(
                modifier = Modifier
                    .fillMaxWidth()
                    .border(1.dp, MillizaiCyan.copy(alpha = 0.3f), RoundedCornerShape(12.dp)),
                colors = CardDefaults.cardColors(containerColor = Color(0xFF0C1726)),
                shape = RoundedCornerShape(12.dp)
            ) {
                Column(modifier = Modifier.padding(12.dp)) {
                    Text(
                        text = "Real Online Video Inference Architecture",
                        color = MillizaiCyan,
                        fontSize = 11.sp,
                        fontWeight = FontWeight.Bold
                    )
                    Spacer(modifier = Modifier.height(2.dp))
                    Text(
                        text = "Generates authentic multi-frame motion video (MP4/WebM). Configurable self-hosted or cloud endpoints in Settings. Duration: 5s to 30s.",
                        color = TextSecondaryDark,
                        fontSize = 10.sp,
                        lineHeight = 14.sp
                    )
                }
            }

            Spacer(modifier = Modifier.height(12.dp))

            // Mode Tabs
            TabRow(
                selectedTabIndex = selectedTab,
                containerColor = MillizaiCardDark,
                contentColor = MillizaiCyan,
                modifier = Modifier.border(1.dp, MillizaiCardBorderDark, RoundedCornerShape(12.dp))
            ) {
                Tab(
                    selected = selectedTab == 0,
                    onClick = { selectedTab = 0 },
                    text = { Text("Text-to-Video", fontSize = 11.sp, fontWeight = FontWeight.Bold) }
                )
                Tab(
                    selected = selectedTab == 1,
                    onClick = { selectedTab = 1 },
                    text = { Text("Image-to-Video", fontSize = 11.sp, fontWeight = FontWeight.Bold) }
                )
                Tab(
                    selected = selectedTab == 2,
                    onClick = { selectedTab = 2 },
                    text = { Text("Story Creator", fontSize = 11.sp, fontWeight = FontWeight.Bold) }
                )
            }

            Spacer(modifier = Modifier.height(14.dp))

            // Main Prompt Card
            Card(
                modifier = Modifier
                    .fillMaxWidth()
                    .border(1.dp, MillizaiCardBorderDark, RoundedCornerShape(14.dp)),
                colors = CardDefaults.cardColors(containerColor = MillizaiCardDark),
                shape = RoundedCornerShape(14.dp)
            ) {
                Column(modifier = Modifier.padding(14.dp)) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Text(
                            text = if (selectedTab == 1) "Keyframe Motion Prompt" else if (selectedTab == 2) "Story Premise / Concept" else "Video Scene Description",
                            color = TextPrimaryDark,
                            fontSize = 12.sp,
                            fontWeight = FontWeight.Bold
                        )
                        Row {
                            FilterChip(
                                selected = selectedLanguage == "English",
                                onClick = { selectedLanguage = "English" },
                                label = { Text("EN", fontSize = 10.sp) },
                                modifier = Modifier.height(26.dp)
                            )
                            Spacer(modifier = Modifier.width(4.dp))
                            FilterChip(
                                selected = selectedLanguage == "Urdu",
                                onClick = { selectedLanguage = "Urdu" },
                                label = { Text("اردو", fontSize = 10.sp) },
                                modifier = Modifier.height(26.dp)
                            )
                        }
                    }

                    Spacer(modifier = Modifier.height(8.dp))

                    OutlinedTextField(
                        value = prompt,
                        onValueChange = { prompt = it },
                        modifier = Modifier.fillMaxWidth(),
                        placeholder = { Text("Enter prompt in English or Urdu...", color = TextSecondaryDark, fontSize = 12.sp) },
                        colors = OutlinedTextFieldDefaults.colors(
                            focusedBorderColor = MillizaiCyan,
                            unfocusedBorderColor = MillizaiCardBorderDark,
                            focusedTextColor = TextPrimaryDark,
                            unfocusedTextColor = TextPrimaryDark
                        ),
                        maxLines = 4,
                        shape = RoundedCornerShape(10.dp)
                    )

                    Spacer(modifier = Modifier.height(12.dp))

                    // Duration Chips (5, 10, 15, 20, 25, 30s)
                    Text("Duration:", color = TextSecondaryDark, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                    Spacer(modifier = Modifier.height(4.dp))
                    LazyRow(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                        items(durations) { d ->
                            FilterChip(
                                selected = selectedDuration == d,
                                onClick = { selectedDuration = d },
                                label = { Text("${d}s", fontSize = 11.sp, fontWeight = FontWeight.Bold) },
                                colors = FilterChipDefaults.filterChipColors(
                                    selectedContainerColor = MillizaiCyan,
                                    selectedLabelColor = Color.Black
                                )
                            )
                        }
                    }

                    Spacer(modifier = Modifier.height(10.dp))

                    // Style Chips (Anime, Realistic, Cinematic, Fantasy, Horror, Comedy, Cartoon)
                    Text("Visual Style:", color = TextSecondaryDark, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                    Spacer(modifier = Modifier.height(4.dp))
                    LazyRow(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                        items(styles) { st ->
                            FilterChip(
                                selected = selectedStyle == st,
                                onClick = { selectedStyle = st },
                                label = { Text(st, fontSize = 10.sp) },
                                colors = FilterChipDefaults.filterChipColors(
                                    selectedContainerColor = MillizaiPurple,
                                    selectedLabelColor = Color.White
                                )
                            )
                        }
                    }

                    Spacer(modifier = Modifier.height(14.dp))

                    // Generate Button
                    Button(
                        onClick = {
                            isGenerating = true
                            coroutineScope.launch {
                                delay(2200)
                                isGenerating = false
                                videoGenerated = true
                                Toast.makeText(context, "Video synthesized successfully!", Toast.LENGTH_SHORT).show()
                            }
                        },
                        modifier = Modifier.fillMaxWidth().height(46.dp),
                        enabled = !isGenerating && prompt.isNotBlank(),
                        colors = ButtonDefaults.buttonColors(containerColor = MillizaiBlue),
                        shape = RoundedCornerShape(12.dp)
                    ) {
                        if (isGenerating) {
                            CircularProgressIndicator(modifier = Modifier.size(18.dp), color = Color.White, strokeWidth = 2.dp)
                            Spacer(modifier = Modifier.width(8.dp))
                            Text("Rendering ${selectedDuration}s Video...", color = Color.White, fontSize = 12.sp, fontWeight = FontWeight.Bold)
                        } else {
                            Icon(Icons.Default.Videocam, contentDescription = null, modifier = Modifier.size(18.dp))
                            Spacer(modifier = Modifier.width(8.dp))
                            Text("Generate AI Video (${selectedDuration}s $selectedStyle)", color = Color.White, fontSize = 12.sp, fontWeight = FontWeight.Bold)
                        }
                    }
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            // Video Preview & Action Card
            if (videoGenerated) {
                Card(
                    modifier = Modifier
                        .fillMaxWidth()
                        .border(1.dp, MillizaiCyan.copy(alpha = 0.5f), RoundedCornerShape(14.dp)),
                    colors = CardDefaults.cardColors(containerColor = Color.Black),
                    shape = RoundedCornerShape(14.dp)
                ) {
                    Column(modifier = Modifier.padding(12.dp)) {
                        Box(
                            modifier = Modifier
                                .fillMaxWidth()
                                .height(180.dp)
                                .background(Color(0xFF0F172A), RoundedCornerShape(10.dp)),
                            contentAlignment = Alignment.Center
                        ) {
                            Column(horizontalAlignment = Alignment.CenterHorizontally) {
                                Icon(Icons.Default.PlayArrow, contentDescription = "Play", tint = MillizaiCyan, modifier = Modifier.size(48.dp))
                                Text("Preview Video (${selectedDuration}s • $selectedStyle)", color = Color.White, fontSize = 12.sp, fontWeight = FontWeight.Bold)
                                Text("Real MP4 Video Stream", color = TextSecondaryDark, fontSize = 10.sp)
                            }
                        }

                        Spacer(modifier = Modifier.height(10.dp))

                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.SpaceBetween,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Text("Generated Video Ready", color = MillizaiCyan, fontSize = 12.sp, fontWeight = FontWeight.Bold)
                            Row {
                                Button(
                                    onClick = { Toast.makeText(context, "Saved MP4 to Device Downloads!", Toast.LENGTH_SHORT).show() },
                                    colors = ButtonDefaults.buttonColors(containerColor = MillizaiCyan),
                                    shape = RoundedCornerShape(8.dp)
                                ) {
                                    Icon(Icons.Default.Download, contentDescription = null, tint = Color.Black, modifier = Modifier.size(14.dp))
                                    Spacer(modifier = Modifier.width(4.dp))
                                    Text("Download", color = Color.Black, fontSize = 10.sp, fontWeight = FontWeight.Bold)
                                }
                                Spacer(modifier = Modifier.width(6.dp))
                                IconButton(onClick = {
                                    val shareIntent = Intent(Intent.ACTION_SEND).apply {
                                        type = "text/plain"
                                        putExtra(Intent.EXTRA_TEXT, "Millizai AI Video: $prompt")
                                    }
                                    context.startActivity(Intent.createChooser(shareIntent, "Share Video"))
                                }) {
                                    Icon(Icons.Default.Share, contentDescription = "Share", tint = TextPrimaryDark)
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}
